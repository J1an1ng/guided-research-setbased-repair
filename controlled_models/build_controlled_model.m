function [system_dynamics_wrapper, system_output_wrapper] = build_controlled_model( ...
        system_dynamics, system_output, model, controller, ...
        state_order, inp_order, params, model_param_conf, check_input_fun)

    if ~exist('check_input_fun', 'var') || isempty(check_input_fun)
        check_input_fun = @(x, u) zeros(length(u), 1);
    end

    system_dynamics_wrapper = @(state_collection, model_params) ...
        system_dynamics( ...
            state_collection, model_params, ...
            model, controller, ...
            state_order, inp_order, params, ...
            model_param_conf, check_input_fun ...
        );

    system_output_wrapper = @(state_collection, model_params) ...
        system_output(state_collection, model_params, model_param_conf);
end
